// Все тексты /tools/zarplata на трёх языках: <head> (seo), интерфейс, FAQ.
// Источники и формулы: SPEC «Расчёт зарплаты» от 24.10.2026, законы сверены
// 24.10.2026 (PAYROLL_CHECKED). Каждый юридический факт в тексте несёт номер
// статьи (НК РК № 214-VIII, Социальный кодекс, Закон об ОСМС, Закон
// № 239-VIII). Сумм и дат в тексты не вшито: они подставляются кодом из
// констант @/lib/payroll (МРП и МЗП там из @/lib/mrp), плейсхолдеры вида
// {name} раскрывает fill(). Суммы в плейсхолдеры приходят уже с знаком ₸.
//
// Термины kk: ОПВ -> МЗЖ, ОПВР -> ЖМЗЖ, СО -> ӘА, ВОСМС -> МӘМС жарналары,
// ООСМС -> МӘМС аударымдары, МЗП -> ЕТЖ, МРП -> АЕК, КГД -> МКК, ИП -> ЖК,
// ТОО -> ЖШС, АО -> АҚ, «на руки» -> «қолға алатын» (один вариант везде) (как в
// /guides/kk/nalogi-ip-uproshchenka-2026). Остальные казахские слова
// (ЖТС, әлеуметтік салық, «қолға алатын», «мүгедектігі бар») не сверены с
// казахским текстом Налогового кодекса: нужна вычитка носителем.
// Длинных и средних тире в строках нет: формулы пишутся с дефисом-минусом.

/** Подстановка {name} -> значение. Неизвестный ключ даёт пустую строку. */
export function fill(template: string, vars: Record<string, string | number>): string {
  return template.replace(/\{(\w+)\}/g, (_m, k: string) => (k in vars ? String(vars[k]) : ''))
}

