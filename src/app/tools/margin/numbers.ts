import type { ToolLang } from '@/lib/tools-i18n'

// Разбор и вывод чисел калькулятора маржи. Отдельно от компонента, чтобы
// проверялось тестом.

/**
 * Число из поля ввода. В РК дробную часть пишут через запятую («12,5»), а
 * тысячи отбивают пробелом («10 000») — прежнее поле type="number» молча
 * превращало такое в 0, и калькулятор считал без комиссии или без цены.
 * Пустое и нечисловое — 0 (как и раньше), знак минуса не теряем: отрицательные
 * значения отсекает уже calculateMargin.
 *
 * Запятая — десятичный знак, КРОМЕ двух случаев, где она явно отбивает тысячи
 * (так пишут по-английски, а на /tools/en/margin это частый ввод цены):
 *  - в числе есть и запятая, и точка («10,000.50») — десятичный знак тот, что
 *    правее, второй знак отбивает разряды («10.000,50» тоже понимаем);
 *  - на en-странице запятая стоит перед группами ровно по три цифры
 *    («10,000», «1,250,000»). На ru/kk «12,500» остаётся 12,5.
 * Несколько точек по три цифры («1.250.000») — тоже разряды, на любом языке.
 * Хвостовые «₸», «тг», «%» и пробелы игнорируются: их часто вставляют вместе с
 * числом из прайса.
 */
export function parseAmount(raw: string, lang: ToolLang = 'ru'): number {
  let s = raw.replace(/[\s  ]/g, '').replace(/(₸|тг\.?|kzt|%)$/i, '')
  if (!s) return 0
  const lastComma = s.lastIndexOf(',')
  const lastDot = s.lastIndexOf('.')
  if (lastComma !== -1 && lastDot !== -1) {
    // Правый знак — десятичный, левый — разделитель разрядов.
    s = lastDot > lastComma ? s.replace(/,/g, '') : s.replace(/\./g, '').replace(',', '.')
  } else if (lastComma !== -1) {
    s = lang === 'en' && /^-?\d{1,3}(,\d{3})+$/.test(s) ? s.replace(/,/g, '') : s.replace(',', '.')
  } else if (/^-?\d{1,3}(\.\d{3}){2,}$/.test(s)) {
    // «1.250.000» — точки только разряды (две и больше групп по три цифры).
    s = s.replace(/\./g, '')
  }
  const n = Number(s)
  return Number.isFinite(n) ? n : 0
}

/** Проценты: «12,5 %» на ru/kk (как пишут в РК), «12.5%» на en. */
export function formatPercent(n: number, lang: ToolLang): string {
  // -0.04 округлилось бы в «-0,0 %» — показываем честный ноль.
  const v = Number.isFinite(n) && Math.abs(n) >= 0.05 ? n : 0
  if (lang === 'en') return `${v.toFixed(1)}%`
  return `${v.toFixed(1).replace('.', ',')} %`
}
