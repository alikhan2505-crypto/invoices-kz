import type { Metadata } from 'next'
import GuideShell from '../GuideShell'
import { getKaspiGuide } from '@/lib/kaspiGuides'
import { KASPI_TIER_ORDER, KASPI_TIERS, formatPercent, withoutVatTimes116 } from '@/lib/kaspiTariff'
import { DataTable, ExampleBlock, LinksBlock, SourceBlock, kaspiMetadata } from '../_kaspi/blocks'

const guide = getKaspiGuide('komissiya-kaspi-s-nds-i-bez-nds')

export const metadata: Metadata = kaspiMetadata(
  guide,
  'ru',
  'комиссия kaspi с ндс или без, комиссия каспи магазина 2026 изменилась, комиссия kaspi 12,5 или 10,9, комиссия kaspi 7,3, комиссия kaspi 15,5',
)

const dec = (n: number) => String(n).replace('.', ',')

export default function Page() {
  return (
    <GuideShell guide={guide} lang="ru">
      <h2>Две колонки в таблице Kaspi</h2>
      <p>
        С 05.01.2026 Kaspi показывает комиссию Магазина на Kaspi.kz без НДС, а налог начисляет отдельно по действующей
        ставке. Поэтому в тарифе у каждой категории две колонки, «Комиссия без НДС» и «Комиссия с НДС». Всего в таблице три
        пары:
      </p>
      <DataTable
        head={['Комиссия без НДС', 'Комиссия с НДС', 'Без НДС × 1,16 (для проверки)']}
        rows={KASPI_TIER_ORDER.map(t => [
          formatPercent(KASPI_TIERS[t].withoutVat),
          formatPercent(KASPI_TIERS[t].withVat),
          `${dec(withoutVatTimes116(t))}%`,
        ])}
      />

      <h2>Почему одну цифру нельзя пересчитать в другую</h2>
      <p>
        Может показаться, что «с НДС» это «без НДС» плюс 16%. Но опубликованные пары так не работают:{' '}
        {dec(KASPI_TIERS.base.withoutVat)} × 1,16 = {dec(withoutVatTimes116('base'))}, а в тарифе{' '}
        {dec(KASPI_TIERS.base.withVat)}. С остальными парами то же самое. Берите в расчёт опубликованное число из таблицы и
        ничего не пересчитывайте.
      </p>

      <h2>Что изменилось с 5 января 2026</h2>
      <ul>
        <li>
          <strong>Порядок показа.</strong> Комиссия указывается без НДС, налог начисляется отдельно и перечисляется в
          бюджет. Комиссия без НДС не изменилась (источник q4467).
        </li>
        <li>
          <strong>НДС с 12% до 16%.</strong> Из-за повышения ставки НДС сумма комиссии с НДС выросла, а комиссия без НДС не
          меняется (q4495).
        </li>
        <li>
          <strong>Старые покупки.</strong> Если покупатель оформил покупку до 04.01.2026 включительно, комиссия считается по
          старым правилам (q4471).
        </li>
        <li>
          <strong>Единая комиссия.</strong> Раньше комиссия на обычные продажи и на акции отличалась. Теперь она едина и
          считается по фактическому среднему значению в категории: за акции с категорийным бонусом и рассрочку до 0-0-12
          дополнительно платить не нужно. Исключение рассрочка 0-0-24: в такие акции комиссия может измениться по условиям
          акции (q3734, q1344). На вопрос, увеличит ли это затраты, Kaspi отвечает «Нет»: в среднем затраты остаются прежними
          (q3733).
        </li>
      </ul>

      <h2>Платят ли меньше те, кто не плательщик НДС</h2>
      <p>
        Нет. На этот вопрос Kaspi отвечает: «Комиссии одинаковые для всех партнеров». НДС начисляется отдельно и
        перечисляется в бюджет (q4521).
      </p>

      <h2>Что ещё подтверждает Kaspi</h2>
      <ul>
        <li>
          Размер комиссии зависит от категории товара и фиксирован. Она взимается только за продажу: если покупатель
          отменит заказ, комиссия вернётся на счёт компании (q1344).
        </li>
        <li>
          Если покупатель оформил возврат товара, комиссия автоматически возвращается на Счёт Kaspi Pay, для этого нужно
          оформить возврат в кабинете продавца (q1347). Эта страница Kaspi датирована 17.01.2025, то есть она старше тарифов
          2026 года.
        </li>
        <li>
          Не путайте с Kaspi Red+: это отдельный продукт со своей таблицей, и Kaspi пишет, что для продавцов Магазина
          комиссия не меняется (q4586, обновлена 04.05.2026). Цифры Red+ в таблице выше не относятся.
        </li>
      </ul>

      <ExampleBlock lang="ru" tiers={KASPI_TIER_ORDER} />
      <LinksBlock
        lang="ru"
        siblings={['komissiya-kaspi-produkty-pitaniya', 'komissiya-kaspi-aksessuary', 'tarify-dostavki-kaspi-magazin']}
      />
      <SourceBlock
        lang="ru"
        ids={['pdf', 'q1344', 'q4467', 'q4471', 'q4495', 'q4521', 'q3734', 'q3733', 'q1347', 'q4586']}
      />
    </GuideShell>
  )
}
