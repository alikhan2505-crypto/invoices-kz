import { describe, it, expect } from 'vitest'
import { renderToStaticMarkup } from 'react-dom/server'
import RuPage from './page'
import KkPage from '../kk/penya-za-prosrochku/page'

// Числа примера берутся из src/lib/nbrkBaseRate.ts; тест фиксирует, что в готовой
// странице они сложились в ту же фразу, что была написана руками до 03.11.2026.
const text = (el: React.ReactElement) => renderToStaticMarkup(el).replace(/<[^>]+>/g, '').replace(/&nbsp;/g, ' ').replace(/\s+/g, ' ')

describe('гайд о пене берёт ставку из одной константы', () => {
  it('русская версия: пример, срок следующего решения и подпись «проверено»', () => {
    const t = text(<RuPage />)
    expect(t).toContain('долг 1 000 000 ₸, просрочка 60 дней, базовая ставка 15,75% годовых (действует с 27.10.2026)')
    expect(t).toContain('(действует с 27.10.2026): 1 000 000 × 0,1575 × 60 / 365 ≈ 25 890 ₸. За полгода просрочки набегает уже около 78 000 ₸ — аргумент')
    expect(t).toContain('(следующее плановое решение — 04.12.2026)')
    expect(t).toContain('Проверено 02.11.2026.')
    expect(t).toContain('базовая ставка НБ РК 15,75% — решение от 23.10.2026, действует с 27.10.2026')
  })

  it('казахская версия: те же числа', () => {
    const t = text(<KkPage />)
    expect(t).toContain('борыш 1 000 000 ₸, кешіктіру 60 күн, базалық мөлшерлеме жылдық 15,75% (27.10.2026 бастап қолданыста)')
    expect(t).toContain('бастап қолданыста): 1 000 000 × 0,1575 × 60 / 365 ≈ 25 890 ₸. Жарты жыл кешіктіруде шамамен 78 000 ₸ жиналады')
    expect(t).toContain('(кезекті жоспарлы шешім — 04.12.2026)')
    expect(t).toContain('02.11.2026 тексерілді.')
    expect(t).toContain('ҰБ базалық мөлшерлемесі 15,75% — 23.10.2026 шешімі, 27.10.2026 бастап қолданыста')
  })
})
