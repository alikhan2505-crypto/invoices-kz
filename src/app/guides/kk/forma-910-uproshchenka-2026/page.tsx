const roman = (n: number) => (n === 1 ? 'I' : 'II')

function calendarLabel(r: CalendarRow): string {
  const p = r.period
  const period = p.type === 'half' ? `${p.year} жылғы ${roman(p.n)} жартыжылдық` : `${p.year} жылғы ${p.n} тоқсан`
  if (r.kind === 'file910') return `${period} үшін 910.00 нысанын тапсыру`
  if (r.kind === 'pay910') return `${period} үшін 910.00 нысаны бойынша салықты төлеу`
  return `${period} үшін 200.00 нысаны, тек қызметкерлер немесе көзінен ұсталатын төлемдер болса`
}

