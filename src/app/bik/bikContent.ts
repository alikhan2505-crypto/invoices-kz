export type Seg = string | { href: string; text: string; external?: boolean }
export type Para = Seg[]
export type FaqItem = { q: string; a: string }

export function paraText(p: Para): string {
  return p.map(s => (typeof s === 'string' ? s : s.text)).join('')
}

export function longDate(lang: BikLang): string {
  return lang === 'kk' ? formatKkDate(NBK_BIK_CHECKED) : formatRuDate(NBK_BIK_CHECKED)
}

/** '2026-10-23' -> '23.10.2026' (для description, где важна длина). */
export function shortDate(): string {
  const [y, m, d] = NBK_BIK_CHECKED.split('-')
  return `${d}.${m}.${y}`
}

