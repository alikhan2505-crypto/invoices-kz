/** Ссылки на соседние страницы банков (все, кроме текущего), для блока «БИК других банков». */
export function otherBankLinks(slug: string, lang: BikLang): { href: string; text: string }[] {
  return BIK_BANK_PAGES.filter(r => r.slug !== slug).map(r => ({
    href: bikBankPath(r.slug!, lang),
    text: lang === 'kk' ? `${r.label} БСК` : `БИК ${r.label}`,
  }))
}

