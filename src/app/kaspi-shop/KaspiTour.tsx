'use client'
import { GuidedTour, type TourStep } from '@/components/DashboardTour'
import { isTourSeen, markTourSeen } from '@/lib/tourSeen'

// Тур первого входа в Kaspi Shop — показывается только когда магазин уже
// подключён (экран подключения сам объясняет себя). «Показан» хранится не в
// profiles, как у дашборда, а в localStorage и cookie на .invoices.kz (см.
// src/lib/tourSeen.ts): без миграции и без лишнего чтения профиля; цена — повтор
// тура на другом устройстве, что для подсказки приемлемо. Отметка ставится при
// показе; повторно запустить тур можно из панели помощи («?» вверху справа).
const ID = 'kaspi'
const LEGACY_KEY = 'kaspi-tour-done'

// Как в DASHBOARD_STEPS: «menu» (мобильный гамбургер) и «menu-desktop»
// (строка разделов) никогда не отрисованы одновременно, GuidedTour сам
// пропустит отсутствующий якорь. «wallet» — глобальный якорь TopUtilityBar.
const STEPS: TourStep[] = [
  {
    anchor: 'kaspi-hero',
    title: 'Гонка цен — главный экран',
    body: 'Бот сам проверяет конкурентов и держит вашу цену выгодной. Здесь видно, работает ли он, сколько товаров выигрывают и сколько упёрлись в минимум.',
  },
  {
    anchor: 'kaspi-rules',
    title: 'Товары и минимальные цены',
    body: 'Ниже — карточки товаров: наша цена, конкурент и минимум. Нажмите на товар, чтобы задать минимальную цену — ниже неё бот не опустится. «Применить сейчас» запускает проверку немедленно.',
  },
  {
    anchor: 'kaspi-cities',
    title: 'Города конкурентов',
    body: 'Выберите города, где у вас есть покупатели, — конкурента и цену проверяем отдельно по каждому городу.',
  },
  {
    anchor: 'menu',
    title: 'Остальные разделы',
    body: 'Заказы с печатью накладных, анализ ниш, показатели качества, добавление товара — всё в меню Kaspi Shop.',
  },
  {
    anchor: 'menu-desktop',
    title: 'Остальные разделы',
    body: 'Заказы с печатью накладных, анализ ниш, показатели качества, добавление товара — переключайтесь в этой строке.',
  },
  {
    anchor: 'wallet',
    title: 'Единый кошелёк',
    body: 'Проверки цен списываются с общего кошелька платформы — пополняется в один клик, баланс виден и на главном экране.',
  },
]

export default function KaspiTour() {
  return (
    <GuidedTour
      steps={STEPS}
      // Хранилища недоступны — тур не показываем (isTourSeen тогда отвечает «показан»):
      // он не должен ломать страницу и не должен лезть при каждом заходе.
      shouldStart={async () => {
        const seen = isTourSeen(ID, [LEGACY_KEY])
        // Уже видели: переносим прежний ключ localStorage в общую cookie и продлеваем её
        // (Safari стирает cookie из скриптов через 7 дней), чтобы другой адрес тур не показал.
        if (seen) markTourSeen(ID)
        return !seen
      }}
      onFinish={async () => markTourSeen(ID)}
    />
  )
}
