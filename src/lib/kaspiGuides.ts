// Страница K1-K8 по slug. Падает, если slug неизвестен, чтобы опечатка не давала пустую страницу.
export function getKaspiGuide(slug: KaspiPageSlug): Guide {
  const guide = KASPI_GUIDES.find(g => g.slug === slug)
  if (!guide) throw new Error(`Unknown Kaspi guide: ${slug}`)
  return guide
}

