// Понятный текст вместо «Kaspi ответил HTTP 500/429» (прогон воронки 07.11.2026, M24). Продавцу нужна причина
// и что делать, а код ответа остаётся в скобках для поддержки.
export function kaspiHttpError(status: number): string {
  if (status === 429) return 'Kaspi просит подождать: слишком много запросов. Повторите через минуту (код 429).'
  if (status === 401 || status === 403) return `Kaspi не принял вход в кабинет. Переподключите магазин (код ${status}).`
  if (status >= 500) return `Kaspi временно не отвечает. Повторите через минуту (код ${status}).`
  return `Kaspi вернул ошибку. Повторите позже (код ${status}).`
}
