// Стоп-фразы агента (ai_agents.stop_phrases): совпадение переводит диалог на
// человека (paused_for_human), и снять паузу можно только вручную. Поэтому
// ложное срабатывание здесь стоит дорого -- бот замолкает для клиента навсегда.
//
// История:
// - до 15.10.2026 совпадение искалось как подстрока: «человек» срабатывал на
//   «нас будет 4 человека», «менеджер» -- на «менеджмент»;
// - 15.10 стало «целым словом» -- и перестали ловиться обычные просьбы
//   («соедините с оператором», «можно менеджера?», «менеджерге қосыңыз»);
// - 16.10 (сейчас): каждое слово фразы -- это основа, после которой допускается
//   окончание до MAX_SUFFIX букв («оператор» ловит «оператором», «операторға»,
//   «менеджера», «менеджерге»), но начало слова по-прежнему должно совпадать
//   («сверхчеловек», «менеджмент» не ловятся). А счёт людей («4 человека»,
//   «количество человек», «на двоих человек») отсекается отдельной защитой:
//   совпадение, начинающееся с «человек…», пропускается, если прямо перед ним
//   стоит число или числительное.
//
// Границы слова -- явные, через Unicode-классы и флаг u: \b в JS без флага u
// после кириллицы не работает вообще (известная ловушка, см. invoiceDrafts.ts).
// Регистр не важен, ё = е. Между словами многословной фразы допускается любой
// пробельный промежуток.

// Буква/цифра/подчёркивание в любом алфавите. Литералы регулярок, а не
// строки -- чтобы обратные слэши не терялись при экранировании.
const NOT_WORD_BEFORE = /(?<![\p{L}\p{N}_])/u.source
const NOT_WORD_AFTER = /(?![\p{L}\p{N}_])/u.source
const BETWEEN_WORDS = /\s+/u.source

// Окончание после основы: «оператор|ом», «менеджер|ге», «человек|а».
// Для коротких слов (предлоги «с», «к») -- не больше одной буквы («со»).
const MAX_SUFFIX = 4
const SHORT_WORD_MAX_SUFFIX = 1
const SHORT_WORD_LEN = 2

function normalize(s: string): string {
  return s.toLowerCase().replace(/ё/g, 'е')
}

function escapeRegExp(s: string): string {
  return s.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')
}

function wordPattern(word: string): string {
  const max = [...word].length <= SHORT_WORD_LEN ? SHORT_WORD_MAX_SUFFIX : MAX_SUFFIX
  return escapeRegExp(word) + `\\p{L}{0,${max}}`
}

function phraseWords(phrase: string): string[] {
  return normalize(phrase).trim().split(/\s+/).filter(Boolean)
}

function buildSource(words: string[]): string {
  return NOT_WORD_BEFORE + words.map(wordPattern).join(BETWEEN_WORDS) + NOT_WORD_AFTER
}

export function stopPhraseRegExp(phrase: string): RegExp | null {
  const words = phraseWords(phrase)
  if (words.length === 0) return null
  return new RegExp(buildSource(words), 'u')
}

// ── Защита от «счёта людей» ─────────────────────────────────────────────
// Совпадение, которое начинается со слова на «человек…», пропускаем, если
// прямо перед ним (через пробел/дефис) стоит число («4 человека», «4-х
// человек») или слово из этого списка. Только для «человек»: людей клиенты
// считают постоянно (бронь, запись, «Количество человек» -- одна из галочек
// сбора данных), а «4 оператора» / «2 менеджера» в переписке не встречаются.
const COUNT_WORDS = new Set([
  // русские числительные (ё уже заменена на е)
  'один', 'одна', 'одного', 'одному', 'одним', 'одном',
  'два', 'две', 'двух', 'двум', 'двумя',
  'три', 'трех', 'трем', 'тремя',
  'четыре', 'четырех', 'четырем', 'четырьмя',
  'пять', 'пяти', 'шесть', 'шести', 'семь', 'семи', 'восемь', 'восьми',
  'девять', 'девяти', 'десять', 'десяти',
  'одиннадцать', 'двенадцать', 'тринадцать', 'четырнадцать', 'пятнадцать',
  'шестнадцать', 'семнадцать', 'восемнадцать', 'девятнадцать',
  'двадцать', 'двадцати', 'тридцать', 'тридцати', 'сорок', 'сорока',
  'пятьдесят', 'шестьдесят', 'семьдесят', 'восемьдесят', 'девяносто', 'сто', 'ста',
  'двое', 'двоих', 'двоим', 'трое', 'троих', 'троим', 'четверо', 'четверых',
  'пятеро', 'пятерых', 'шестеро', 'шестерых', 'семеро', 'семерых',
  'восьмеро', 'восьмерых', 'девятеро', 'девятерых', 'десятеро', 'десятерых',
  'пара', 'пару', 'пары', 'несколько', 'нескольких', 'нескольким',
  'много', 'многих', 'мало', 'сколько', 'скольких',
  'количество', 'количества', 'количеству', 'число', 'числа', 'кол-во',
  // казахские
  'бір', 'екі', 'үш', 'төрт', 'бес', 'алты', 'жеті', 'сегіз', 'тоғыз', 'он',
  'жиырма', 'отыз', 'қырық', 'елу', 'жүз',
  'екеу', 'үшеу', 'төртеу', 'бесеу', 'алтау', 'жетеу', 'сегізеу', 'тоғызеу', 'онау',
  'бірнеше', 'неше', 'қанша', 'саны', 'сан',
])

const COUNTED_STEM = 'человек'

// Последнее «слово» перед позиции idx, если между ними только пробелы/дефисы/
// тире. Цифры внутри (4, 4х, 4-х) тоже считаются.
const PREV_TOKEN = /([\p{L}\p{N}]+(?:-[\p{L}\p{N}]+)*)[\s\-–—]*$/u

function precededByCount(text: string, idx: number): boolean {
  const m = PREV_TOKEN.exec(text.slice(0, idx))
  if (!m) return false
  const token = m[1]
  if (/\p{N}/u.test(token)) return true
  return COUNT_WORDS.has(token)
}

export function matchesStopPhrase(text: string, phrase: string): boolean {
  const words = phraseWords(phrase)
  if (words.length === 0) return false
  const norm = normalize(text)
  const re = new RegExp(buildSource(words), 'gu')
  const guarded = words[0].startsWith(COUNTED_STEM)
  for (const m of norm.matchAll(re)) {
    if (guarded && precededByCount(norm, m.index ?? 0)) continue
    return true
  }
  return false
}

export function findStopPhraseMatch(text: string, phrases: string[]): boolean {
  return phrases.some(p => typeof p === 'string' && matchesStopPhrase(text, p))
}
