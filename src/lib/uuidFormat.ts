// Проверка формата uuid для идентификаторов из публичного ввода (тело запроса,
// сегмент пути). Колонки id в базе - uuid, и PostgREST на «abc» отвечает ошибкой
// 22P02, которую лежащие ниже загрузчики бросают как исключение: анонимный
// вызов с мусорным id заканчивался 500. Мусор отсекаем до обращения к базе.
const UUID_RE = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/i

export function isUuid(value: unknown): value is string {
  return typeof value === 'string' && UUID_RE.test(value)
}
