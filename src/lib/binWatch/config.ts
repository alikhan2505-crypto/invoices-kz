/** Живых проверок реестров за сутки на весь крон (верхний предел из решения основателя). */
export const BIN_WATCH_DAILY_MAX = 300

/**
 * Запас общей квоты реестров для бесплатных инструментов. Крон не стартует новую
 * проверку, если registryLoadToday (общая нагрузка за день, куда входит и сам
 * крон) уже достигла REGISTRY_DAILY_GLOBAL минус этот запас: страница проверки
 * контрагента не остаётся без квоты из-за ночного прогона.
 */
export const BIN_WATCH_TOOL_RESERVE = 100

/** Префикс ключа суточного счётчика крона в tool_kontragent_checks: 'watch:YYYY-MM-DD'. */
export const BIN_WATCH_COUNTER_PREFIX = 'watch:'

/** Один БИН проверяется не чаще, чем раз в это время (с запасом на дрожание крона: 20 ч, не 24). */
export const BIN_WATCH_MIN_RECHECK_MS = 20 * 3_600_000

/** Кэш bin_lookup_cache для крона свежее суток: ночной прогон не должен читать вчерашнее. */
export const BIN_WATCH_CACHE_TTL_MS = 20 * 3_600_000

/**
 * maxDuration функции крона, секунды. Next 16 читает `export const maxDuration`
 * в route.ts статически: импортированный идентификатор он не раскрывает и `next
 * build` падает (Unknown identifier), поэтому в /api/cron/bin-watch/route.ts
 * стоит ЛИТЕРАЛ 300, а эта константа лишь зеркало для расчёта ёмкости ниже.
 * Менять только вместе с литералом (их равенство проверяет route.test.ts).
 */
export const BIN_WATCH_MAX_DURATION_S = 300
/** Новые проверки БИН не стартуют позже этого момента от начала прогона (одна проверка с повторами тянется до ~35 с). */
export const BIN_WATCH_LOOKUP_DEADLINE_MS = 230_000
/** Новые письма не стартуют позже этого момента; остаток уйдёт на следующий день. До maxDuration (300 с) остаётся запас на сбой Resend. */
export const BIN_WATCH_EMAIL_DEADLINE_MS = 270_000

/**
 * Темп холодных проверок: не чаще одной в этот интервал (старт к старту; если
 * проверка сама заняла дольше, паузы нет). Холодная проверка с extras - это
 * ~6 запросов к КГД (налогоплательщик/НДС, неблагонадёжные, ликвидация, долг,
 * режим) и 1-3 к egov (gbd_ul + aisoip с повторами). Ключ КГД держит 40 запросов
 * в минуту (REGISTRY_DAILY_GLOBAL, toolQuota.ts), ключ egov тоже 40 в минуту и
 * общий с инструментом контрагента и /tools/kp. 9 с на БИН = ~6,7 БИН в минуту =
 * ~40 запросов КГД в минуту в самом худшем случае (ИП + все повторы), то есть мы
 * не упираемся в 429, а серия не превращает поля в null.
 */
export const BIN_WATCH_PACE_MS = 9_000

/**
 * Честная суточная ёмкость крона: сколько БИН реально проверяется за один
 * прогон при темпе выше и дедлайне проверок. BIN_WATCH_DAILY_MAX (300) - потолок
 * предохранителя, а не ёмкость: по времени больше этого числа не успеть. Если
 * на слежении больше БИН, чем ёмкость, порядок «самые давно проверенные первыми»
 * делает круговой обход: каждый БИН проверяется раз в ceil(N / ёмкость) суток.
 * Hobby даёт только суточные кроны и 300 с на функцию; поднять ёмкость можно
 * тарифом Vercel (частые кроны) или общим токен-бакетом и параллелизмом.
 */
export const BIN_WATCH_DAILY_CAPACITY = Math.floor(BIN_WATCH_LOOKUP_DEADLINE_MS / BIN_WATCH_PACE_MS)

/**
 * Результат с пустыми признаками (часть реестров не ответила) - «частичный».
 * Его попытка записывается не как «только что проверено», а как сделанная
 * (MIN_RECHECK - PARTIAL_RETRY) назад: повтор доступен через PARTIAL_RETRY, а в
 * очереди такой БИН идёт чуть раньше целых (но сдвиг меньше суток, поэтому
 * целые строки не голодают).
 */
export const BIN_WATCH_PARTIAL_RETRY_MS = 6 * 3_600_000
/** Сколько строк слежения крон берёт за прогон (хватает с большим запасом). */
export const BIN_WATCH_ROWS_PER_RUN = 2000

/** Событие каталога уведомлений (src/lib/notificationPrefs.ts), по которому владелец включает и выключает письмо. */
export const BIN_WATCH_MAIL_EVENT = 'bin_watch_changed' as const

