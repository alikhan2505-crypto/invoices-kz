// «Следить за этим БИН» (решение основателя 29.10.2026): контрагента можно
// поставить на слежение; раз в сутки крон перепроверяет БИН и, если результат
// ухудшился, шлёт одно письмо владельцу списка. Здесь только константы и чистые
// решения (без сети и без базы): годятся и клиентской странице, и маршрутам API.

import { getActivePlan } from '@/lib/plan'

/**
 * Админ-гейт (правило основателя: каждую новую секцию он лично проверяет до
 * открытия клиентам). true: кнопка «Следить», страница списка, API и письма
 * доступны ТОЛЬКО is_admin; крон для не-админов ничего не обрабатывает и не
 * шлёт. Открыть всем = поменять на false ЗДЕСЬ, больше нигде. Тот же приём,
 * что SETUP_WIZARD_ADMIN_ONLY в src/lib/aiAgent/setupWizard.ts.
 */
export const BIN_WATCH_ADMIN_ONLY = true

/** Доступна ли функция этому пользователю. Единственная проверка гейта в коде. */
export function canUseBinWatch(isAdmin: boolean | null | undefined): boolean {
  return BIN_WATCH_ADMIN_ONLY ? isAdmin === true : true
}

/**
 * Лимиты списка слежения на аккаунт: единственное место, где они записаны.
 * Free 5 (решение основателя), Про 50 (выбор исполнителя: «больше на Pro»).
 * Базовый, пробный и бонусные дни считаются как Free: платная ёмкость только у Про.
 */
export const BIN_WATCH_LIMITS = { free: 5, pro: 50 } as const

/**
 * Лимит конкретного аккаунта. Про определяем через getActivePlan: там уже
 * учтены срок тарифа, бонус, триал и админ-переопределение (is_admin считается
 * Про: у него все canX открыты). canKpAvrNakl открыт только у действующего Про
 * и у админа.
 */
export function binWatchLimit(profile: unknown, now: Date = new Date()): number {
  return getActivePlan(profile, now).canKpAvrNakl ? BIN_WATCH_LIMITS.pro : BIN_WATCH_LIMITS.free
}

