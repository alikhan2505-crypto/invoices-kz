import { describe, it, expect } from 'vitest'
import { numberToWordsRu, amountInWordsKzt } from './amountWords'

describe('numberToWordsRu', () => {
  const cases: Array<[number, string]> = [
    [0, 'ноль'],
    [1, 'один'],
    [21, 'двадцать один'],
    [100, 'сто'],
    [1000, 'одна тысяча'],
    [2000, 'две тысячи'],
    [4000, 'четыре тысячи'],
    [5000, 'пять тысяч'],
    [11000, 'одиннадцать тысяч'],
    [14000, 'четырнадцать тысяч'],
    [21000, 'двадцать одна тысяча'],
    [22000, 'двадцать две тысячи'],
    [84000, 'восемьдесят четыре тысячи'],
    [85000, 'восемьдесят пять тысяч'],
    [101000, 'сто одна тысяча'],
    [112000, 'сто двенадцать тысяч'],
    [149400, 'сто сорок девять тысяч четыреста'],
    [1000000, 'один миллион'],
    [2000000, 'два миллиона'],
    [5000000, 'пять миллионов'],
    [21000000, 'двадцать один миллион'],
    [1234567, 'один миллион двести тридцать четыре тысячи пятьсот шестьдесят семь'],
    [3001001, 'три миллиона одна тысяча один'],
    [2000000000, 'два миллиарда'],
    [-21000, 'минус двадцать одна тысяча'],
  ]
  it.each(cases)('%d', (n, words) => expect(numberToWordsRu(n)).toBe(words))
})

describe('amountInWordsKzt', () => {
  it('целая сумма: 00 тиын', () => {
    expect(amountInWordsKzt(149400)).toBe('сто сорок девять тысяч четыреста тенге 00 тиын')
    expect(amountInWordsKzt(84000)).toBe('восемьдесят четыре тысячи тенге 00 тиын')
  })
  it('тиыны берутся из дробной части', () => {
    expect(amountInWordsKzt(1500.5)).toBe('одна тысяча пятьсот тенге 50 тиын')
    expect(amountInWordsKzt(21000.07)).toBe('двадцать одна тысяча тенге 07 тиын')
  })
  it('округление до 100 тиын переносится в тенге', () => {
    expect(amountInWordsKzt(9.999)).toBe('десять тенге 00 тиын')
  })
})
