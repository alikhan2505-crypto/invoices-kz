/** Дата проверки данных по первоисточникам (ISO). */
export const MRP_CHECKED = '2026-10-24'
/** Дата, с которой действует МРП 2026 (ISO). */
export const MRP_EFFECTIVE = '2026-01-01'

/** Значения в таблице пересчёта на странице. */
export const MRP_CONVERSION_STEPS: readonly number[] = [1, 5, 10, 14, 25, 30, 100, 200, 500, 1000, 10_000]

/** Число МРП в тенге. По умолчанию МРП 2026; вторым аргументом можно подставить другой размер. */
export function mrpToTenge(count: number, mrp: number = MRP_2026): number {
  return Math.round(count * mrp)
}

/** Группировка тысяч неразрывным пробелом: 2595000000 -> «2 595 000 000». Не зависит от ICU. */
export function formatNumber(n: number): string {
  return String(Math.round(n)).replace(/\B(?=(\d{3})+(?!\d))/g, ' ')
}

/** «4 325 ₸» с неразрывными пробелами. */
export function formatTenge(n: number): string {
  return `${formatNumber(n)} ₸`
}

export interface MrpConversionRow {
  mrp: number
  tenge: number
}

export function mrpConversionRows(mrp: number = MRP_2026): MrpConversionRow[] {
  return MRP_CONVERSION_STEPS.map(count => ({ mrp: count, tenge: mrpToTenge(count, mrp) }))
}

