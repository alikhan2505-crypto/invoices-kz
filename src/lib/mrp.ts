/** Месячный расчётный показатель на 2026 год, ₸ (Закон № 239-VIII, ст. 7, пп. 4). */
export const MRP_2026 = 4_325
/** Минимальная заработная плата на 2026 год, ₸ (Закон № 239-VIII, ст. 7, пп. 1). */
export const MZP_2026 = 85_000
/** Предельный годовой доход для упрощённой декларации, в МРП (НК, ст. 723, п. 1, пп. 1). */
export const SIMPLIFIED_INCOME_LIMIT_MRP = 600_000
/** Порог оборота для постановки на учёт по НДС, в МРП (НК, ст. 99, п. 4, пп. 2). */
