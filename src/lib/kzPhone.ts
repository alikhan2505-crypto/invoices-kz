// Ввод казахстанского номера телефона: одно место вместо восьми копий (кабинет,
// счета, /upgrade, Kaspi, публичная страница счёта). Формат «+7 777 123 45 67».
//
// Прежние копии считали первую набранную цифру кодом страны, поэтому номер без кода
// («777 123 45 67», так он лежит в контактах) терял последнюю цифру при вставке.
// Теперь национальные цифры — десять после «+7»; лишний код страны распознаётся по
// длине: одиннадцать цифр, первая 7 или 8. Пока набрано меньше одиннадцати цифр,
// «7» считается началом самого номера (национальные номера Казахстана начинаются с 7),
// а на одиннадцатой цифре строка перестраивается, если это был код.

const GROUPS: Array<[number, number]> = [[0, 3], [3, 6], [6, 8], [8, 10]]

/** Десять национальных цифр из набранного или вставленного текста (меньше десяти, пока номер не набран). */
export function nationalDigits(value: string): string {
  let rest = value.trim()
  // «+7» в начале — наш собственный префикс (или набранный код): в номер он не входит.
  if (rest.startsWith('+7')) rest = rest.slice(2)
  let d = rest.replace(/\D/g, '')
  if (d.length >= 11 && (d[0] === '7' || d[0] === '8')) d = d.slice(1)
  // «8» вместо «+7»: национальные номера с 8 не начинаются.
  else if (d[0] === '8') d = d.slice(1)
  return d.slice(0, 10)
}

/** Для поля ввода: «+7 777 123 45 67» по мере набора; пустое поле остаётся пустым. */
export function formatKzPhone(value: string): string {
  const d = nationalDigits(value)
  if (!d) return ''
  const parts = GROUPS.map(([from, to]) => d.slice(from, to)).filter(Boolean)
  return `+7 ${parts.join(' ')}`
}

/** Полный номер для отправки: «+77771234567», либо null, если цифр не десять. */
export function normalizeKzPhone(value: string): string | null {
  const d = nationalDigits(value)
  return d.length === 10 ? `+7${d}` : null
}
