/** НДС, выделенный из суммы с НДС: round(сумма - сумма / 1,16) - как в generateNakladnaya. */
export function vatFromGross(amount: number): number {
  return Math.round(amount - amount / (1 + Z2_VAT_RATE / 100))
}

export function z2Example() {
  const lines = EXAMPLE_ROWS.map((r, i) => {
    const amount = r.qty * r.price
    return { n: i + 1, ...r, amount, vat: vatFromGross(amount) }
  })
  const total = lines.reduce((s, l) => s + l.amount, 0)
  const vatLinesSum = lines.reduce((s, l) => s + l.vat, 0)
  const vatTotal = vatFromGross(total)
  return {
    lines,
    total,
    /** НДС по итогу, если продавец плательщик НДС и цены с НДС. */
    vatTotal,
    vatLinesSum,
    /** Сумма без НДС для плательщика НДС. */
    netTotal: total - vatTotal,
    positions: lines.length,
  }
}

