/** Сообщение человеку: что и как заказать. Собирается из выбранных справок. */
export function buildPersonMessage(selected: readonly RequestableCertificate[]): string {
  const list = selected.map(c => `• ${c.title}: ${c.href}`).join('\n')
  return [
    'Здравствуйте! Для оформления прошу прислать электронные справки:',
    list,
    '',
    'Как получить (бесплатно, обычно около 10 минут): откройте ссылку на egov.kz или в приложении eGov mobile, нажмите «Заказать услугу», выберите «На себя» и подпишите запрос ЭЦП или SMS-паролем.',
    'Готовую справку скачайте в личном кабинете (раздел «Сообщения») и пришлите мне файлом.',
  ].join('\n')
}

