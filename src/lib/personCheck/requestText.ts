export interface RequestableCertificate {
  id: string
  title: string
  shows: string
  /** Страница справки на egov.kz (её открывает сам человек и заказывает «На себя»). */
  href: string
  code: string
  /** Что ещё спросит форма. */
  extra: string | null
}

