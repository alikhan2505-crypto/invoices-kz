// Проверка физического лица по ИИН (макет 30.10.2026, вкладка «Физлицо · СБ» на
// /tools/kontragent). Только открытые реестры: исполнительные производства Минюста
// и, если у человека есть ИП, данные КГД. Судимость, розыск и закрытые базы не
// проверяются и не будут: сведения о судимости закон выдаёт только самому человеку.
//
// Админ-гейт (правило основателя: каждую новую секцию он лично проверяет до
// открытия клиентам). true: вкладка и API доступны ТОЛЬКО is_admin. Открыть всем =
// поменять на false ЗДЕСЬ, больше нигде; вместе с этим решается лимит проверок на
// пользователя (сейчас лимита нет: вызывать может только админ).

export const PERSON_CHECK_ADMIN_ONLY = true

/** Доступна ли проверка физлица этому пользователю. Единственная проверка гейта в коде. */
export function canUsePersonCheck(isAdmin: boolean | null | undefined): boolean {
  return PERSON_CHECK_ADMIN_ONLY ? isAdmin === true : true
}
