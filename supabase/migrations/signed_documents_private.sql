-- 15.10.2026: бакет signed-documents (загруженные договоры, снимки счетов и
-- договоров, подписанные ЭЦП, карточки SIGEX) становится закрытым.
--
-- До этого любой файл бакета открывался по вечной публичной ссылке, а сами
-- ссылки лежали в contracts.file_url и document_signatures.*_pdf_url.
-- Код (src/lib/signedDocuments.ts) с 15.10 уже:
--   - пишет в эти колонки путь объекта, а не ссылку;
--   - старые публичные ссылки читает как пути — данные переписывать не надо;
--   - отдаёт файлы только сервером (служебная роль: download / createSignedUrl)
--     после проверки владельца или public_token документа.
-- Всё это работает и на публичном бакете, поэтому порядок такой: сначала
-- выкатить код, потом выполнить этот файл в SQL Editor.
--
-- Политику INSERT для authenticated ("Signed documents authenticated upload")
-- НЕ трогаем: браузер владельца по-прежнему сам загружает договор и снимок
-- счёта перед подписанием. SELECT-политик у бакета нет и не нужно —
-- читает только служебная роль.
--
-- Что остаётся открытым намеренно (решение основателя, не этот файл):
-- /api/documents/<id>/document|card отдаёт уже ПОДПИСАННЫЙ документ без входа
-- и без токена — по id строки подписи, который публикует страница проверки
-- /api/documents/verify/<sigexId> (номер SIGEX напечатан на бумаге и на
-- карточке). Значит, подписанный договор читается любым, у кого есть его
-- номер SIGEX, и после закрытия бакета. Закрытие бакета защищает
-- неподписанные договоры и старые вечные ссылки.

update storage.buckets
set public = false
where id = 'signed-documents';

-- Проверка: должно вернуть public = false.
select id, public from storage.buckets where id = 'signed-documents';

