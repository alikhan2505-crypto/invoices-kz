-- ai_agents.kaspi_catalog_off (18.10.2026): «не использовать магазин Kaspi».
-- true = агент не называет товары, цены, доставку и не присылает ссылки на
-- магазин (даже если у аккаунта есть активный магазин Kaspi). По умолчанию
-- false = поведение как раньше (закреплённый магазин или активный магазин
-- аккаунта). Код работает и до применения миграции (флаг читается как false;
-- сохранение «отключить» до неё вернёт понятную ошибку).
alter table public.ai_agents
  add column if not exists kaspi_catalog_off boolean not null default false;
